#!/usr/bin/env node
// Regenerate client/dsh-tokens.ts from the stylesheets an installed dsh ships.
//
// dsh's theme plugin inlines its token stylesheets into its browser bundle, so the token names of a
// given dsh release are read from `@deepseek-ai/dsh-client-ui-theme/lib/client.js`:
//
//   node scripts/extract-dsh-tokens.mjs <path to dsh-client-ui-theme/lib/client.js>
//
// Run it when the supported dsh range moves, then review the diff and the theme mapping.

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const source = process.argv[2]
if (source === undefined) {
  console.error('usage: node scripts/extract-dsh-tokens.mjs <dsh-client-ui-theme/lib/client.js>')
  process.exit(1)
}
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const bundle = readFileSync(source, 'utf8')
const themePackage = JSON.parse(readFileSync(path.join(path.dirname(source), '..', 'package.json'), 'utf8'))

/** Every inlined stylesheet: `var <name>_css_default = "<css>";`. */
const sheets = [...bundle.matchAll(/var (\w+)_css_default = ("(?:[^"\\]|\\.)*");/g)]
  .map(([, name, literal]) => ({ name, css: JSON.parse(literal) }))
if (sheets.length === 0) {
  console.error('extract-dsh-tokens: no inlined stylesheet found; the bundle layout changed')
  process.exit(1)
}

/** Token names declared inside rule blocks whose selector matches `selector`. */
const declared = selector => {
  const names = new Set()
  for (const { css } of sheets) {
    for (const [, selectors, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      if (!selector(selectors.trim())) continue
      for (const [, name] of body.matchAll(/(--dsw-[a-z0-9-]+)\s*:/g)) names.add(name)
    }
  }
  return names
}

const light = declared(selectors => selectors === 'body')
const dark = declared(selectors => selectors === 'body[data-ds-dark-theme]')
const all = declared(() => true)
const sorted = names => [...names].sort()

/** Alias-layer and shell tokens a theme may restate; static ramps, type and geometry are excluded. */
const skinnable = name => /^--dsw-(alias|specific|shadow|linear)-/.test(name) || name === '--dsw-menu-surface-fill'
const radius = sorted([...all].filter(name => name.startsWith('--dsw-radius-')))
/** Tokens with a value for both palettes, either restated by the dark block or palette-independent. */
const skin = sorted([...light].filter(skinnable))
const darkOnlyMissing = skin.filter(name => !dark.has(name))

const list = names => names.map(name => `  '${name}',`).join('\n')
const output = `/**
 * Token names dsh ${themePackage.version} declares in its theme stylesheets, generated by
 * \`scripts/extract-dsh-tokens.mjs\` from \`@deepseek-ai/dsh-client-ui-theme/lib/client.js\`.
 * Do not edit by hand; regenerate when the supported dsh range moves.
 */

/** The dsh release these names were read from. */
export const DSH_TOKENS_VERSION = '${themePackage.version}'

/**
 * Alias-layer and shell tokens the light palette (\`body\`) declares: the surface a theme restates.
 * Static colour ramps, type tokens and radii are not part of it.
 */
export const SKIN_TOKENS = [
${list(skin)}
] as const

/** Skin tokens the dark palette does not restate, so both palettes share the light value. */
export const SHARED_SKIN_TOKENS = [
${list(darkOnlyMissing)}
] as const

/** Corner radius tokens (\`:root\` in base.css). */
export const RADIUS_TOKENS = [
${list(radius)}
] as const

export type SkinToken = typeof SKIN_TOKENS[number]
`
writeFileSync(path.join(root, 'client/dsh-tokens.ts'), output)
console.log(`extract-dsh-tokens: ${skin.length} skin tokens, ${radius.length} radius tokens from dsh ${themePackage.version}`)
